def get_remarks(equipment_name: str) -> str:
    for key, value in REMARKS_BY_NAME.items():
        if key in equipment_name:
            return value
    return "1. 每日使用前后清洁设备表面与工作区域，保持无积尘、无杂物。2. 定期检查各紧固件与连接件是否松动，必要时拧紧。3. 按周期为运动部位加注润滑油或润滑脂，防止干磨。4. 发现异常声响、震动或温升时，应立即停机检查。5. 长期停用前应清洁设备并覆盖防尘罩。6. 维护保养时应悬挂停机标识，确保安全操作。"


def main():
    supabase = create_client(URL, KEY)
    rows = (
        supabase.table("entity_store")
        .select("id, data")
        .eq("entity_type", "maintenance_plans")
        .execute()
    )
    if not rows.data:
        print("未找到保养计划记录")
        return

    updated = 0
    for row in rows.data:
        data = row["data"]
        mp_id = data.get("id")
        eq_name = data.get("equipment_name") or ""
        data["remarks"] = get_remarks(eq_name)
        supabase.table("entity_store").update({"data": data}).eq("id", mp_id).eq(
            "entity_type", "maintenance_plans"
        ).execute()
        print(f"已更新 {data.get('code')}: {eq_name}")
        updated += 1

    print(f"\n完成，共更新 {updated}/{len(rows.data)} 条保养计划记录")


if __name__ == "__main__":
    main()
