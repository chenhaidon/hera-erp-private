def main():
    supabase = create_client(URL, KEY)
    rows = (
        supabase.table("entity_store")
        .select("id, data")
        .eq("entity_type", "equipment")
        .execute()
    )
    if not rows.data:
        print("未找到设备记录")
        return

    updated = 0
    for row in rows.data:
        data = row["data"]
        eq_id = data.get("id")
        if eq_id not in REMARKS:
            print(f"跳过无备注配置的设备: {eq_id}")
            continue
        data["remarks"] = REMARKS[eq_id]
        supabase.table("entity_store").update({"data": data}).eq("id", eq_id).eq(
            "entity_type", "equipment"
        ).execute()
        print(f"已更新 {eq_id}: {data.get('name')}")
        updated += 1

    print(f"\n完成，共更新 {updated}/{len(rows.data)} 条设备记录")


if __name__ == "__main__":
    main()
